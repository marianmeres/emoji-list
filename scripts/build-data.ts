/**
 * Generates the `src/data/*.ts` modules from the Unicode `emoji-test.txt` data file.
 *
 * Usage:
 *     deno run -A scripts/build-data.ts              # uses local scripts/data/emoji-test.txt
 *     deno run -A scripts/build-data.ts --download   # fetches the latest from unicode.org first
 *
 * Notes:
 * - Only `fully-qualified` and `component` entries are included.
 * - Skin tone modifiers and their variant sequences are excluded (default
 *   skin tone only), which keeps the maps reasonably small.
 */

import { join } from "@std/path";

const SRC_URL = "https://unicode.org/Public/emoji/latest/emoji-test.txt";
const SRC_FILE = join(import.meta.dirname!, "data", "emoji-test.txt");
const OUT_DIR = join(import.meta.dirname!, "..", "src", "data");

const SKIN_TONES = new Set(["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"]);
const STATUSES = new Set(["fully-qualified", "component"]);

if (Deno.args.includes("--download")) {
	console.log(`Downloading ${SRC_URL} ...`);
	const res = await fetch(SRC_URL);
	if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText}`);
	await Deno.writeTextFile(SRC_FILE, await res.text());
}

const raw = await Deno.readTextFile(SRC_FILE);

//
let dataVersion = "";
let groupMajor = "";
let groupMinor = "";

const keyMap: Record<string, string> = {};
const codeMap: Record<string, string> = {};
const keyToGroupMap: Record<string, [string, string]> = {};
const groupToKeyMap: Record<string, string[]> = {};
const fulltextMap: Record<string, string> = {};

for (const line of raw.split("\n").map((l) => l.trim())) {
	if (!line) continue;

	if (line.startsWith("#")) {
		dataVersion ||= line.match(/^# Version: (.+)$/)?.[1] ?? "";
		const g = line.match(/^# group: (.+)$/)?.[1];
		if (g) groupMajor = toGroup(g);
		const s = line.match(/^# subgroup: (.+)$/)?.[1];
		if (s) groupMinor = toGroup(s);
		continue;
	}

	// eg: "1F62E 200D 1F4A8 ; fully-qualified # 😮‍💨 E13.1 face exhaling"
	const m = line.match(/^([0-9A-F ]+?)\s*;\s*([\w-]+)\s*#\s*\S+\s+E[\d.]+\s+(.+)$/);
	if (!m) continue;

	const [, codepoints, status, name] = m;
	if (!STATUSES.has(status)) continue;

	const points = codepoints.split(/\s+/).filter(Boolean);
	// default skin tone only
	if (points.some((p) => SKIN_TONES.has(p))) continue;

	const hex = points.join("-").toLowerCase();
	const key = toKey(name);

	if (keyMap[key]) {
		console.warn(`WARN: Key "${key}" already exists, skipping "${name}" (${hex})`);
		continue;
	}
	if (codeMap[hex]) {
		console.warn(`WARN: Hex "${hex}" already exists, skipping "${name}"`);
		continue;
	}

	keyMap[key] = hex;
	codeMap[hex] = key;
	keyToGroupMap[key] = [groupMajor, groupMinor];
	(groupToKeyMap[groupMajor] ??= []).push(key);
	(groupToKeyMap[`${groupMajor}/${groupMinor}`] ??= []).push(key);
	fulltextMap[key] = name;
}

if (!dataVersion) throw new Error("Unable to parse data version");
const count = Object.keys(keyMap).length;
if (count < 1500) throw new Error(`Suspiciously low entry count: ${count}`);

//
const HEADER = `// GENERATED FILE - DO NOT EDIT
// Generated by scripts/build-data.ts from Unicode emoji-test.txt v${dataVersion}
// (https://unicode.org/Public/emoji/latest/emoji-test.txt)
`;

function write(filename: string, content: string) {
	Deno.writeTextFileSync(join(OUT_DIR, filename), HEADER + content);
	console.log(`Written ${join("src", "data", filename)}`);
}

const json = (o: unknown) => JSON.stringify(o, null, "\t");

Deno.mkdirSync(OUT_DIR, { recursive: true });

write(
	"version.ts",
	`
/** The Unicode Emoji data version these maps were generated from. */
export const EMOJI_DATA_VERSION: string = ${JSON.stringify(dataVersion)};
`,
);

write(
	"key-map.ts",
	`
/** Emoji key to hex code map (eg \`grinningFace -> 1f600\`). */
export const emojiKeyMap: Record<string, string> = ${json(keyMap)};
`,
);

write(
	"code-map.ts",
	`
/** Emoji hex code to key map (eg \`1f600 -> grinningFace\`). */
export const emojiCodeMap: Record<string, string> = ${json(codeMap)};
`,
);

write(
	"groups.ts",
	`
/** Emoji key to \`[group, subgroup]\` map. */
export const emojiKeyToGroupMap: Record<string, [string, string]> = ${
		json(keyToGroupMap)
	};

/** Group (\`group\` or \`group/subgroup\`) to list of emoji keys map. */
export const emojiGroupToKeyMap: Record<string, string[]> = ${json(groupToKeyMap)};
`,
);

write(
	"fulltext.ts",
	`
/** Emoji key to full text name map (eg \`grinningFace -> "grinning face"\`). */
export const emojiFulltextMap: Record<string, string> = ${json(fulltextMap)};
`,
);

console.log(`\nOK (${count} emojis, data version ${dataVersion})\n`);

//////////////////////////////////////////////////////////////////////////////////////////

function ucfirst(s: string): string {
	return s.charAt(0).toUpperCase() + s.slice(1);
}

function lcfirst(s: string): string {
	return s.charAt(0).toLowerCase() + s.slice(1);
}

function unaccent(s: string): string {
	return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
}

/** "Smileys & Emotion" -> "smileys and emotion" */
function toGroup(name: string): string {
	return unaccent(name).replace(/&/g, "and").toLowerCase().trim();
}

/** "flag: Wales" -> "flagWales" */
function toKey(name: string): string {
	return lcfirst(
		unaccent(name)
			.replace(/#/g, "hash")
			.replace(/\*/g, "star")
			.replace(/&/g, "and")
			.replace(/[’']/g, "")
			.replace(/\W/g, " ")
			.split(/\s+/)
			.filter(Boolean)
			.map(ucfirst)
			.join(""),
	);
}
